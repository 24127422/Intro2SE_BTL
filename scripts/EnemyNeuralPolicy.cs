	public static List<EnemyPlanAction> Predict(
		float relX, float relY,
		float playerVelX, float playerVelY,
		float dist, float hpPercent,
		bool isPatrol, bool isChase)
	{
		float[] input =
		{
			relX / DetectRange,
			relY / DetectRange,
			playerVelX / PlayerWalkSpeed,
			playerVelY / PlayerWalkSpeed,
			dist / DetectRange,
			hpPercent / 100f,
			isPatrol ? 1f : 0f,
			isChase ? 1f : 0f,
		};

		int hiddenDim = B1.Length;
		float[] hidden = new float[hiddenDim];
		for (int j = 0; j < hiddenDim; j++)
		{
			float sum = B1[j];
			for (int i = 0; i < input.Length; i++)
				sum += input[i] * W1[i, j];
			hidden[j] = Mathf.Max(0f, sum); // ReLU
		}

		int outputDim = B2.Length;
		float[] output = new float[outputDim];
		for (int j = 0; j < outputDim; j++)
		{
			float sum = B2[j];
			for (int i = 0; i < hiddenDim; i++)
				sum += hidden[i] * W2[i, j];
			output[j] = sum;
		}

		var plan = new List<EnemyPlanAction>();
		int numSteps = outputDim / 6;
		for (int step = 0; step < numSteps; step++)
		{
			int baseIdx = step * 6;
			int bestClass = 0;
			float bestScore = float.MinValue;
			for (int c = 0; c < 5; c++)
			{
				if (output[baseIdx + c] > bestScore)
				{
					bestScore = output[baseIdx + c];
					bestClass = c;
				}
			}

			float duration = Mathf.Clamp(output[baseIdx + 5], 0.1f, 3f);
			plan.Add(new EnemyPlanAction { Direction = Keys[bestClass], Duration = duration });
		}

		return plan;
	}
